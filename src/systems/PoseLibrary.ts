export function lerpPose(a: SkeletonPose, b: SkeletonPose, t: number): SkeletonPose {
  const out = {} as SkeletonPose;
  for (const k of Object.keys(a) as (keyof SkeletonPose)[]) {
    out[k] = {
      x: a[k].x + (b[k].x - a[k].x) * t,
      y: a[k].y + (b[k].y - a[k].y) * t,
    };
  }
  return out;
}
